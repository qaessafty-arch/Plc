#!/usr/bin/env python3
"""Totals bom.csv for the three configurations in USD and IQD -> ../../DOCUMENTATION/REPORTS/budget.md"""
import csv, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", ".."))
import machine_params as P

rows = list(csv.DictReader(open(os.path.join(HERE, "bom.csv"))))
cfg = [("qty_edu", "1 Educational prototype"), ("qty_semi", "2 Semi-industrial machine"), ("qty_ind", "3 Industrial machine")]
groups = sorted({r["group"] for r in rows}, key=[r["group"] for r in rows].index)
tot = {c: {g: 0.0 for g in groups} for c, _ in cfg}
for r in rows:
    for c, _ in cfg:
        tot[c][r["group"]] += float(r[c]) * float(r["unit_usd"])
iqd = lambda u: f"{u * P.USD_TO_IQD:,.0f}"
o = ["# Estimated budget\n",
     "> Generated by `ELECTRICAL/BOM/budget.py` from `bom.csv`. **Every unit price is an estimate** made without "
     "supplier quotations, except two items whose range was taken from public supplier listings seen on 2026-11-11 "
     "(marked in the `price_basis` column). No price in this project is a verified purchase price. Freight, customs, "
     "VAT and local distributor margins for Iraq are covered only by the contingency line.\n",
     f"Exchange rate: 1 USD = {P.USD_TO_IQD} IQD (Central Bank of Iraq cash selling rate, checked 2026-11-11; "
     "the parallel market rate may differ).\n",
     "| Group | " + " | ".join(n for _, n in cfg) + " |", "|---|" + "---:|" * 3]
for g in groups:
    o.append(f"| {g} | " + " | ".join(f"{tot[c][g]:,.0f}" for c, _ in cfg) + " |")
sub = {c: sum(tot[c].values()) for c, _ in cfg}
cont = {"qty_edu": 0.15, "qty_semi": 0.20, "qty_ind": 0.20}
o.append("| **Subtotal USD** | " + " | ".join(f"**{sub[c]:,.0f}**" for c, _ in cfg) + " |")
o.append("| Contingency + freight/customs allowance | " + " | ".join(f"{cont[c]:.0%} = {sub[c] * cont[c]:,.0f}" for c, _ in cfg) + " |")
o.append("| **Total USD** | " + " | ".join(f"**{sub[c] * (1 + cont[c]):,.0f}**" for c, _ in cfg) + " |")
o.append("| **Total IQD** | " + " | ".join(f"**{iqd(sub[c] * (1 + cont[c]))}**" for c, _ in cfg) + " |")
o.append("| Expected accuracy of this estimate | +/-40 % | +/-30 % | +/-35 % |\n")
o += ["## What each configuration is\n",
      "| | 1 Educational prototype | 2 Semi-industrial | 3 Industrial |", "|---|---|---|---|",
      "| Purpose | teach/prove the VFFS sequence | small factory production | continuous production with QA records |",
      "| Frame | aluminium profile, bench size | welded 304 stainless | welded 304, hygienic detailing, documented materials |",
      "| Film / bag | <= 250 mm web, 60-110 mm bags | 420 mm web, 80-200 mm bags | same + gusset / hole-punch options |",
      "| Weighing | single weigh bucket + vibratory tray (self-built) | economy 10-head multihead (bought) | branded 10/14-head, approvable for trade |",
      "| Film drive | closed-loop stepper | 0.4 kW servo | servo; servo jaws as later option |",
      "| Control | S7-1200 1214C + 4\" panel | S7-1200 1215C + KTP700 + safety relays | fail-safe S7-1200 F + KTP700 + monitoring PC |",
      "| Quality devices | none | none (manual sampling) | checkweigher, metal detector, coder, N2 |",
      "| Expected speed | 8-15 bags/min (theoretical) | 30-45 bags/min (theoretical) | 40-60 bags/min (theoretical) |",
      "| Suitable for selling food? | no | only after safety validation and hygiene review | yes, after conformity assessment |\n",
      "## Operating cost outline (semi-industrial, theoretical)\n",
      "Energy and film per hour are in `DOCUMENTATION/ENGINEERING/03_ENGINEERING_CALCULATIONS.md` section 8. "
      "Add: 1 operator + shared loader; product give-away (simulated ~1.4 % at 40 g, see `SIMULATION/weigher_results.json`); "
      "wear parts per year - PTFE tape, 2 knives, 1 pair pull belts, 2 heater sets, thermocouples: roughly 400-700 USD [estimate]; "
      "annual weigher calibration service.\n",
      f"\nBOM lines: {len(rows)}. Items with `model_status` = *verified* had their order number and key data checked against "
      "manufacturer data on 2026-11-11; *from memory - confirm* must be checked in the manufacturer catalogue before ordering; "
      "*generic* means the specification is binding and the brand is free; *to quote/select* needs a supplier offer."]
os.makedirs(os.path.join(HERE, "..", "..", "DOCUMENTATION", "REPORTS"), exist_ok=True)
open(os.path.join(HERE, "..", "..", "DOCUMENTATION", "REPORTS", "budget.md"), "w").write("\n".join(o) + "\n")
print("\n".join(o[4:14]))
